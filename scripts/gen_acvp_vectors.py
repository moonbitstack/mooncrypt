#!/usr/bin/env python3
"""Write NIST ACVP vectors as MoonBit test tables.

    python scripts/gen_acvp_vectors.py <dir holding the downloaded JSON> [--full]

Each family is two files from ACVP-Server, the prompt with the inputs and the
expected results with the outputs, joined on `tcId`:

    gh api -H "Accept: application/vnd.github.raw" \\
      "repos/usnistgov/ACVP-Server/contents/gen-val/json-files/ML-KEM-keyGen-FIPS203/prompt.json" \\
      > ML-KEM-keyGen-FIPS203.prompt.json
    gh api -H "Accept: application/vnd.github.raw" \\
      "repos/usnistgov/ACVP-Server/contents/gen-val/json-files/ML-KEM-keyGen-FIPS203/expectedResults.json" \\
      > ML-KEM-keyGen-FIPS203.expectedResults.json

The vectors are NIST's own expected output, which is what the validation
programme compares against; this script only reshapes them.

`--full` emits every case. Without it SLH-DSA signing keeps a fixed subsample:
one full replay of the slow parameter sets is hours of hashing, and the suite
runs on four targets. Every other family is always complete.
"""

from __future__ import annotations

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent / "src"
SOURCE = "https://github.com/usnistgov/ACVP-Server/tree/master/gen-val/json-files"

BANNER = [
    "// Generated by scripts/gen_acvp_vectors.py from NIST's ACVP-Server; rerun it",
    "// rather than editing.",
    f"// {SOURCE}",
]


def load(cache: pathlib.Path, family: str):
    """(group, cases) of one ACVP family, the outputs joined onto the inputs."""

    def read(kind):
        return json.loads((cache / f"{family}.{kind}.json").read_text(encoding="utf-8"))

    prompt = read("prompt")
    expected = read("expectedResults")
    outputs = {
        str(t["tcId"]): t for g in expected["testGroups"] for t in g["tests"]
    }
    groups = []
    for group in prompt["testGroups"]:
        cases = []
        for test in group["tests"]:
            case = dict(test)
            case.update(outputs[str(test["tcId"])])
            cases.append(case)
        groups.append((group, cases))
    return groups


def table(name, entry, rows, chunk=32):
    """One array, split over functions so no single initialiser gets long."""
    if not rows:
        return ["///|", f"let {name} : Array[{entry}] = []", ""]
    out = []
    parts = []
    for i in range(0, len(rows), chunk):
        fn = f"{name}_part{i // chunk}"
        parts.append(fn)
        out += [
            "///|",
            f"fn {fn}() -> Array[{entry}] {{",
            "  [",
            *[f"    {row}" for row in rows[i:i + chunk]],
            "  ]",
            "}",
            "",
        ]
    out += ["///|", f"let {name} : Array[{entry}] = {' + '.join(f'{p}()' for p in parts)}", ""]
    return out


def write(path: pathlib.Path, body):
    path.write_text("\n".join(BANNER + [""] + body + [""]), encoding="utf-8", newline="\n")
    print(f"wrote {path.relative_to(ROOT.parent)}")


def h(text: str) -> str:
    return f'"{text.lower()}"'


# --------------------------------------------------------------------- ML-KEM


def mlkem(cache: pathlib.Path, _full: bool):
    sets = {}

    for group, cases in load(cache, "ML-KEM-keyGen-FIPS203"):
        sets.setdefault(param(group["parameterSet"]), {})["keygen"] = cases

    for group, cases in load(cache, "ML-KEM-encapDecap-FIPS203"):
        name = param(group["parameterSet"])
        slot = sets.setdefault(name, {})
        if group["function"] == "encapsulation":
            slot["encapsulation"] = cases
        elif group["function"] == "decapsulation":
            slot["decapsulation"] = cases
        elif group["function"] == "encapsulationKeyCheck":
            slot["encapsulation_key_check"] = cases
        else:
            slot["decapsulation_key_check"] = cases

    for name, blocks in sorted(sets.items()):
        body = []
        for key, cases in blocks.items():
            if key == "keygen":
                rows = [
                    f"({h(c['d'])}, {h(c['z'])}, {h(c['ek'])}, {h(c['dk'])}),"
                    for c in cases
                ]
                entry = "(String, String, String, String)"
            elif key == "encapsulation":
                rows = [
                    f"({h(c['ek'])}, {h(c['m'])}, {h(c['c'])}, {h(c['k'])})," for c in cases
                ]
                entry = "(String, String, String, String)"
            elif key == "decapsulation":
                rows = [f"({h(c['dk'])}, {h(c['c'])}, {h(c['k'])})," for c in cases]
                entry = "(String, String, String)"
            else:
                field = "ek" if key == "encapsulation_key_check" else "dk"
                rows = [
                    f"({h(c[field])}, {str(c['testPassed']).lower()})," for c in cases
                ]
                entry = "(String, Bool)"
            body += table(f"{key}_{name.lower()}", entry, rows)
        write(ROOT / "pq" / "mlkem" / f"vectors_{name.lower()}_test.mbt", body)


# --------------------------------------------------------------------- ML-DSA

# Every signature family is sampled: a signing vector is a key and a signature,
# which is kilobytes each, and the point of the set is to cover each interface
# combination, not to replay the same interface hundreds of times.
SAMPLE = 3


def pick(cases, n=SAMPLE):
    return cases[:n]


def mldsa(cache: pathlib.Path, full: bool):
    keygen = {}
    for group, cases in load(cache, "ML-DSA-keyGen-FIPS204"):
        keygen[param(group["parameterSet"])] = cases

    siggen, sigver = {}, {}
    for family, sink in (("ML-DSA-sigGen-FIPS204", siggen), ("ML-DSA-sigVer-FIPS204", sigver)):
        for group, cases in load(cache, family):
            name = param(group["parameterSet"])
            sink.setdefault(name, []).append((group, pick(cases, 999) if full else pick(cases)))

    for name in sorted(keygen):
        body = table(
            f"keygen_{name.lower()}",
            "(String, String, String)",
            [f"({h(c['seed'])}, {h(c['pk'])}, {h(c['sk'])})," for c in keygen[name]],
        )

        outer, inner = [], []
        for group, cases in siggen.get(name, []):
            for c in cases:
                rnd = h(c.get("rnd", ""))
                if group["signatureInterface"] == "external":
                    tag = "pure" if group["preHash"] == "pure" else "prehash:" + c["hashAlg"].lower()
                    outer.append(
                        f"({h(tag)}, {h(c['message'])}, {h(c.get('context', ''))}, "
                        f"{h(c['sk'])}, {rnd}, {h(c['signature'])}),"
                    )
                elif group["externalMu"]:
                    inner.append(
                        f"({h('mu')}, {h(c['sk'])}, {h(c['mu'])}, {rnd}, {h(c['signature'])}),"
                    )
                else:
                    inner.append(
                        f"({h('msg')}, {h(c['sk'])}, {h(c['message'])}, {rnd}, "
                        f"{h(c['signature'])}),"
                    )
        body += table(
            f"siggen_{name.lower()}",
            "(String, String, String, String, String, String)",
            outer,
        )

        ver, ver_inner = [], []
        for group, cases in sigver.get(name, []):
            for c in cases:
                if group["signatureInterface"] == "external":
                    tag = "pure" if group["preHash"] == "pure" else "prehash:" + c["hashAlg"].lower()
                    ver.append(
                        f"({h(tag)}, {h(c['pk'])}, {h(c['message'])}, {h(c.get('context', ''))}, "
                        f"{h(c['signature'])}, {str(c['testPassed']).lower()}),"
                    )
                else:
                    tag = "mu" if group["externalMu"] else "msg"
                    subject = c["mu"] if group["externalMu"] else c["message"]
                    ver_inner.append(
                        f"({h(tag)}, {h(c['pk'])}, {h(subject)}, {h(c['signature'])}, "
                        f"{str(c['testPassed']).lower()}),"
                    )
        body += table(
            f"sigver_{name.lower()}",
            "(String, String, String, String, String, Bool)",
            ver,
        )
        write(ROOT / "pq" / "mldsa" / f"vectors_{name.lower()}_test.mbt", body)

        # The internal interface is not part of the public surface, so its
        # vectors live in the package's own white-box tests.
        inner_body = table(
            f"siggen_internal_{name.lower()}",
            "(String, String, String, String, String)",
            inner,
        )
        inner_body += table(
            f"sigver_internal_{name.lower()}",
            "(String, String, String, String, Bool)",
            ver_inner,
        )
        write(ROOT / "pq" / "mldsa" / f"vectors_internal_{name.lower()}_wbtest.mbt", inner_body)


def param(name: str) -> str:
    """ML-KEM-768 -> K768, ML-DSA-65 -> D65, SLH-DSA-SHA2-128f -> Sha2_128f."""
    if name.startswith("ML-KEM-"):
        return "K" + name.rsplit("-", 1)[1]
    if name.startswith("ML-DSA-"):
        return "D" + name.rsplit("-", 1)[1]
    if name.startswith("SLH-DSA-"):
        return name[len("SLH-DSA-"):].replace("-", "_")
    raise ValueError(name)


def main():
    cache = pathlib.Path(sys.argv[1])
    full = "--full" in sys.argv
    mlkem(cache, full)
    mldsa(cache, full)


if __name__ == "__main__":
    main()
