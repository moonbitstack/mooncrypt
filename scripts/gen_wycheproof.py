"""Write the Wycheproof AEAD vectors as MoonBit test tables.

    python scripts/gen_wycheproof.py <dir holding aes_gcm_test.json and chacha20_poly1305_test.json>

The JSON files are C2SP/wycheproof's testvectors_v1; rerun after they change.
"""

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent / "src"
SOURCE = "https://github.com/C2SP/wycheproof/tree/main/testvectors_v1"

TARGETS = {
    "aes_gcm_test.json": ROOT / "aead" / "gcm" / "wycheproof_test.mbt",
    "chacha20_poly1305_test.json": ROOT / "aead" / "chachapoly" / "wycheproof_test.mbt",
}


def table(path):
    data = json.loads(path.read_text(encoding="utf-8"))
    rows = []
    for group in data["testGroups"]:
        for t in group["tests"]:
            valid = "true" if t["result"] == "valid" else "false"
            fields = [t["key"], t["iv"], t["aad"], t["msg"], t["ct"] + t["tag"]]
            quoted = ", ".join(f'"{f}"' for f in fields)
            rows.append(f"  ({t['tcId']}, {quoted}, {valid}),")
    return data["numberOfTests"], rows


def main():
    src = pathlib.Path(sys.argv[1])
    for name, out in TARGETS.items():
        count, rows = table(src / name)
        assert count == len(rows), (name, count, len(rows))
        text = [
            f"// Generated by scripts/gen_wycheproof.py from Wycheproof's {name}; rerun it rather",
            "// than editing.",
            f"// {SOURCE}",
            "",
            "///|",
            "/// (tcId, key, nonce, aad, plaintext, ciphertext with tag, valid)",
            "let vectors : Array[(Int, String, String, String, String, String, Bool)] = [",
            *rows,
            "]",
            "",
        ]
        out.write_text("\n".join(text), encoding="utf-8", newline="\n")
        print(f"wrote {len(rows)} vectors to {out}")


BRAINPOOL = {
    "brainpoolP256r1": ("BrainpoolP256r1", 32),
    "brainpoolP384r1": ("BrainpoolP384r1", 48),
    "brainpoolP512r1": ("BrainpoolP512r1", 64),
}

# p, a, b of each curve (RFC 5639 §3.2–3.4), to tell a point that is genuinely
# off the curve from one whose invalidity is only in the DER envelope.
