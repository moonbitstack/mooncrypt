#!/usr/bin/env python3
"""Write the BLAKE3 test table from the project's published test vectors.

The vectors live at https://github.com/BLAKE3-team/BLAKE3/blob/master/test_vectors/test_vectors.json.
Pass the file as the first argument, or let the script fetch it. The generated
MoonBit file is committed; CI only reads it, so the build never needs a network.

    python3 scripts/gen_blake3_vectors.py [vectors.json]
"""

import json
import pathlib
import sys
import urllib.request

SOURCE = (
    "https://raw.githubusercontent.com/BLAKE3-team/BLAKE3/master/test_vectors/test_vectors.json"
)
OUT = pathlib.Path(__file__).resolve().parent.parent / "src/hash/blake3/vectors_test.mbt"


def load(path):
    if path:
        return json.loads(pathlib.Path(path).read_text(encoding="utf-8"))
    with urllib.request.urlopen(SOURCE) as response:
        return json.loads(response.read().decode("utf-8"))


def main():
    data = load(sys.argv[1] if len(sys.argv) > 1 else None)
    cases = data["cases"]
    lines = [
        "// Copyright 2026 Leo Cheng",
        "// SPDX-License-Identifier: Apache-2.0",
        "",
        "// Generated by scripts/gen_blake3_vectors.py. Do not edit.",
        "",
        "///|",
        "/// The 32-byte key the keyed vectors use.",
        f'let vector_key : String = "{data["key"]}"',
        "",
        "///|",
        "/// The context string the derivation vectors use.",
        f'let vector_context : String = "{data["context_string"]}"',
        "",
        "///|",
        "/// One case: an input length, then the plain, keyed and derived digests",
        "/// read to 131 bytes. 131 is past 64, so every case also exercises a",
        "/// second and third block of root output.",
        "let vector_cases : Array[(Int, String, String, String)] = [",
    ]
    for case in cases:
        lines.append(
            "  (\n"
            f"    {case['input_len']},\n"
            f'    "{case["hash"]}",\n'
            f'    "{case["keyed_hash"]}",\n'
            f'    "{case["derive_key"]}",\n'
            "  ),"
        )
    lines += ["]", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(cases)} cases -> {OUT}")


if __name__ == "__main__":
    main()
